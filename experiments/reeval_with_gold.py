# reeval_with_gold.py - retroactive correctness re-evaluation.
import json
import re
from pathlib import Path

ROOT = Path(__file__).parent.parent
OUT = ROOT / "logs" / "reeval"
OUT.mkdir(parents=True, exist_ok=True)


def find_arith_expressions(text):
    return re.findall(r"\d+[+\-*/]\d+(?:[+\-*/]\d+)*", text or "")


def find_numbers(final_str):
    return [int(x) for x in re.findall(r"-?\d+", final_str or "")]


def extract_arith_gold(prompt_text):
    exprs = find_arith_expressions(prompt_text)
    if not exprs:
        return None
    out = []
    for e in exprs:
        try:
            out.append((e, eval(e)))
        except Exception:
            pass
    return out if out else None


def check_arith(prompt_text, final_str):
    expected = extract_arith_gold(prompt_text)
    if expected is None:
        return None, [], [], 0
    exp_vals = [v for (_, v) in expected]
    got = find_numbers(final_str)
    matched = sum(1 for v in exp_vals if v in got)
    return (matched == len(exp_vals)), exp_vals, got, matched


def extract_final_from_messages(messages):
    for m in messages:
        if m.get("role") == "assistant":
            content = m.get("content", "")
            for match in re.finditer(r"```json\s*(\{.*?\})\s*```", content, re.DOTALL):
                try:
                    obj = json.loads(match.group(1))
                    if "final" in obj:
                        return str(obj["final"])
                except Exception:
                    continue
    return None


def process_samples(path):
    rows = []
    n_arith = 0
    n_arith_correct = 0
    if not path.exists():
        return rows, n_arith, n_arith_correct
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        try:
            r = json.loads(line)
        except Exception:
            continue
        msgs = r.get("messages", [])
        user_text = next((m["content"] for m in msgs if m.get("role") == "user"), "")
        final = extract_final_from_messages(msgs)
        if final is None:
            rows.append({"user_prompt": user_text[:100], "final_emitted": None, "correct": None})
            continue
        result, exp, got, matched = check_arith(user_text, final)
        if result is not None:
            n_arith += 1
            if result:
                n_arith_correct += 1
        rows.append({
            "user_prompt": user_text[:100],
            "final_emitted": final[:50],
            "expected_vals": exp,
            "got_vals": got,
            "matched_count": matched,
            "correct": result,
        })
    return rows, n_arith, n_arith_correct


def main():
    print("=== Retroactive gold re-evaluation ===")
    totals = {"n_arith": 0, "n_arith_correct": 0, "n_total": 0, "n_emitted": 0}
    for gen_dir in sorted((ROOT / "logs" / "full_run3").glob("gen-*")):
        samples = gen_dir / "samples.jsonl"
        rows, n_arith, n_arith_correct = process_samples(samples)
        n_total = len(rows)
        n_emitted = sum(1 for r in rows if r.get("final_emitted") is not None)
        er = n_emitted / max(1, n_total)
        cr_line = ""
        if n_arith:
            cr_line = " corr_n=" + str(n_arith) + "/" + str(n_arith_correct)
        print(gen_dir.name + ": n=" + str(n_total) + " emission=" +
              str(round(100 * er, 1)) + "%" + cr_line)
        for r in rows:
            if r.get("correct") is False:
                print("  WRONG: exp=" + str(r.get("expected_vals")) +
                      " got=" + str(r.get("got_vals")) + " prompt=\"" +
                      r.get("user_prompt", "")[:60] + "...\"")
        totals["n_arith"] += n_arith
        totals["n_arith_correct"] += n_arith_correct
        totals["n_total"] += n_total
        totals["n_emitted"] += n_emitted
    o_emi = totals["n_emitted"] / max(1, totals["n_total"])
    o_cor = (totals["n_arith_correct"] / totals["n_arith"]) if totals["n_arith"] else None
    print("OVERALL: samples=" + str(totals["n_total"]) +
          " emission=" + str(round(100 * o_emi, 1)) + "%")
    if o_cor is not None:
        print("        correctness (arith n=" + str(totals["n_arith"]) + "): " +
              str(totals["n_arith_correct"]) + "/" + str(totals["n_arith"]) +
              " = " + str(round(100 * o_cor, 1)) + "%")
    out_data = {
        "total_samples": totals["n_total"],
        "emission_rate": o_emi,
        "n_arith": totals["n_arith"],
        "n_arith_correct": totals["n_arith_correct"],
        "correctness_rate_on_arith": o_cor,
    }
    (OUT / "correctness_summary.json").write_text(json.dumps(out_data, indent=2), encoding="utf-8")
    md = []
    md.append("# Retroactive Correctness Re-Evaluation (Round 12)")
    md.append("")
    md.append("Generated by experiments/reeval_with_gold.py")
    md.append("")
    md.append("- Total episodes inspected: " + str(totals["n_total"]))
    md.append("- JSON final emission rate: **" + str(round(100 * o_emi, 1)) + "%** (the historical structural-emission metric)")
    if o_cor is not None:
        gap = 100 * (o_emi - o_cor)
        md.append("- Correctness on arith subset (n=" + str(totals["n_arith"]) + "): **" +
                  str(round(100 * o_cor, 1)) + "%**")
        md.append("- Gap emission - correctness = **" + str(round(gap, 1)) + " pp**")
    md.append("")
    md.append("Honest reading: the historical headline metric is JSON emission, not answer correctness.")
    (OUT / "correctness_summary.md").write_text("\n".join(md), encoding="utf-8")
    print("Wrote logs/reeval/correctness_summary.{json,md}")


if __name__ == "__main__":
    main()
